#!/usr/bin/env python3
"""logo_to_c.py: turn the logo image and a QR code into the splash screen data.

    logo_to_c.py <logo.pgm> <qr.txt> <out.c>

logo.pgm is a binary PGM (P5, 8-bit) the size of the screen, dark ink on a
light background. qr.txt is `qrencode -t ASCII -m 0` output: one row per
line, "##" for a dark module and "  " for a light one. `make -f host.mk logo`
makes both from keyandcable_logo.svg and the site's URL.

Each logo pixel becomes one of four shades, 0 = background (the glass field)
to 3 = full ink, and the screen is stored row by row from the top left as
runs: one byte per run, bits 7-6 the shade, bits 5-0 the run length minus 1
(1-64 pixels). The QR code is stored as one bit per module, a row per word.
src/pr53_logo.h describes the format for the firmware side.
"""

import sys

W, H = 480, 320
MAX_RUN = 64

# Ink fraction from grey level: at or above LIGHT counts as background, at or
# below DARK as full ink. The logo's ivory (#fff8e7) lands on 0, its outlines
# and black key (#2b2b2b, #000) and the cable (#4a4a4a) on 3, and the jack
# plug (#989898) on 1. Anti-aliased edges fall in between.
LIGHT, DARK = 240, 50


def read_pgm(path):
    with open(path, "rb") as f:
        data = f.read()
    fields, pos = [], 0
    while len(fields) < 4:                 # magic, width, height, maxval
        while data[pos:pos + 1].isspace():
            pos += 1
        if data[pos:pos + 1] == b"#":      # comment line
            pos = data.index(b"\n", pos) + 1
            continue
        end = pos
        while not data[end:end + 1].isspace():
            end += 1
        fields.append(data[pos:end])
        pos = end
    pos += 1                               # the single whitespace before pixels
    if fields[0] != b"P5" or int(fields[3]) != 255:
        sys.exit(f"{path}: need an 8-bit binary PGM (P5)")
    w, h = int(fields[1]), int(fields[2])
    if (w, h) != (W, H):
        sys.exit(f"{path}: is {w}x{h}, need {W}x{H}")
    return data[pos:pos + w * h]


def read_qr(path):
    with open(path) as f:
        rows = [ln.rstrip("\n") for ln in f if ln.strip("\n")]
    n = len(rows)
    if not 21 <= n <= 32 or any(len(r) != 2 * n for r in rows):
        sys.exit(f"{path}: expected a square QR code, 21 to 32 modules a side")
    return [[row[2 * c] == "#" for c in range(n)] for row in rows]


def shade(grey):
    ink = (LIGHT - grey) / (LIGHT - DARK)
    return min(3, max(0, round(ink * 3)))


def encode(pixels):
    shades = [shade(g) for g in pixels]
    out, i = bytearray(), 0
    while i < len(shades):
        s, n = shades[i], 1
        while i + n < len(shades) and shades[i + n] == s and n < MAX_RUN:
            n += 1
        out.append((s << 6) | (n - 1))
        i += n
    return out, shades


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    rle, shades = encode(read_pgm(sys.argv[1]))
    assert sum((b & 63) + 1 for b in rle) == W * H
    counts = [shades.count(s) for s in range(4)]
    qr = read_qr(sys.argv[2])

    lines = [
        "// pr53_logo.c: GENERATED by logo/logo_to_c.py from logo/keyandcable_logo.svg",
        "// and a QR code for https://keyandcable.com. Don't edit; change the logo or",
        "// the script and run `make -f host.mk logo`.",
        "//",
        f"// Logo: {W}x{H}, {len(rle)} runs; pixels per shade 0-3: {', '.join(map(str, counts))}.",
        "// Format: see pr53_logo.h.",
        "",
        '#include "pr53_logo.h"',
        "",
        "const uint8_t pr53_logo_rle[] = {",
    ]
    for k in range(0, len(rle), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in rle[k:k + 16]) + ",")
    lines += ["};", "", "const uint32_t pr53_logo_rle_len = sizeof(pr53_logo_rle);", ""]
    lines += [f"const uint8_t pr53_qr_n = {len(qr)};", "", "const uint32_t pr53_qr_rows[] = {"]
    for row in qr:
        bits = sum(1 << c for c, dark in enumerate(row) if dark)
        art = "".join("#" if dark else "." for dark in row)
        lines.append(f"    0x{bits:08x},  // {art}")
    lines += ["};", ""]
    with open(sys.argv[3], "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {sys.argv[3]}: logo {len(rle)} bytes for {W}x{H} "
          f"(shades 0-3: {counts}), QR {len(qr)}x{len(qr)}")


if __name__ == "__main__":
    main()
