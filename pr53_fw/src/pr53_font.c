static const Glyph *find_glyph(char c) {
    for (size_t i = 0; i < sizeof(FONT)/sizeof(FONT[0]); i++)
        if (FONT[i].c == c) return &FONT[i];
    return &FONT[0]; // space
}

static int glyph_w(int scale) { return (5 + 1) * scale; } // 5 cols + 1 space

static void draw_glyph(int x, int y, const Glyph *g, int scale, uint16_t color) {
    for (int cx = 0; cx < 5; cx++) {
        uint8_t colbits = g->col[cx];
        for (int ry = 0; ry < 7; ry++) {
            if (colbits & (1 << ry)) {
                ili9488_fill_rect(x + cx*scale, y + ry*scale, scale, scale, color);
            }
        }
    }
}

void font_text(int x, int y, const char *s, int scale, uint16_t color) {
    int cx = x;
    for (; *s; s++) {
        draw_glyph(cx, y, find_glyph(*s), scale, color);
        cx += glyph_w(scale);
    }
}

static int text_px_w(const char *s, int scale) {
    return (int)strlen(s) * glyph_w(scale);
}

void font_text_centered(int cx, int y, const char *s, int scale, uint16_t color) {
    font_text(cx - text_px_w(s, scale)/2, y, s, scale, color);
}

void font_itoa(char *buf, int v) {
    if (v == 0) { buf[0] = '0'; buf[1] = 0; return; }
    char tmp[12]; int n = 0, neg = 0;
    if (v < 0) { neg = 1; v = -v; }
    while (v) { tmp[n++] = '0' + v % 10; v /= 10; }
    int i = 0;
    if (neg) buf[i++] = '-';
    while (n) buf[i++] = tmp[--n];
    buf[i] = 0;
}

void font_box(int x, int y, int w, int h, uint16_t color) {
    ili9488_fill_rect(x, y, w, 1, color);
    ili9488_fill_rect(x, y + h - 1, w, 1, color);
    ili9488_fill_rect(x, y, 1, h, color);
    ili9488_fill_rect(x + w - 1, y, 1, h, color);
}

void font_kbd_icon(int x, int y, uint16_t color) {
    font_box(x, y, 30, 18, color);
    for (int i = 1; i < 5; i++)
        ili9488_fill_rect(x + i*6, y, 1, 18, color);
}

void font_drum_icon(int x, int y, uint16_t color) {
    // simple circle-ish: a filled square with a dot (placeholder)
    font_box(x, y, 20, 18, color);
    ili9488_fill_rect(x + 8, y + 7, 4, 4, color);
}
